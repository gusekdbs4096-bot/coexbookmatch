/*
 * BOOK MATCH - 레벨 설계 (수학적으로 검증됨)
 * ------------------------------------------------------------
 *  cols x rows        : 카드 배열 (총 카드 수 = cols * rows)
 *  groups             : 각 그룹(=한 권의 책)에 필요한 매치 카드 수의 배열
 *                        예) [2,2,3,3] -> 2장 매치가 필요한 책 2권 + 3장
 *                        매치가 필요한 책 2권 = 총 카드 4+6=10장
 *  timeLimit          : 제한시간(초)
 *
 *  중요한 불변식: cols * rows === groups.reduce((a,b)=>a+b, 0)
 *  (아래 각 레벨 옆 주석에 실제 계산값을 적어 두었습니다. 이 배열을 수정할
 *  경우 반드시 이 합이 카드 수와 같은지 다시 확인하세요. 어긋나면 게임 시작 시
 *  콘솔에 에러가 발생하도록 game.js에서 검증합니다.)
 *
 *  설계 원칙(한 레벨 안에서 매치 개수를 섞지 않음):
 *   - 레벨 1~6 : 전부 2 MATCH. 난이도는 책 종류(카드 수)만 늘려서 조절
 *                (2권 -> 3 -> 4 -> 6 -> 8 -> 10권)
 *   - 레벨 7~10: 전부 3 MATCH로 전환. 마찬가지로 책 종류/카드 수만 늘려서
 *                조절 (8권 -> 9 -> 10 -> 12그룹)
 *  같은 레벨 안에서 2장 찾기와 3장 찾기가 동시에 섞여 있으면 플레이어가
 *  헷갈려한다는 피드백을 받아, 레벨 단위로 매치 개수를 통일했습니다.
 *
 *  그룹 수(=groups.length)만큼 서로 다른 책이 필요합니다. BOOKS 배열의 앞에서
 *  부터 순서대로 배정되며, 그룹 수가 BOOKS 전체 권수(11권)보다 많아지면
 *  일부 책이 두 번째 그룹으로 재사용됩니다. 레벨 10에서만 발생합니다
 *  (12그룹인데 책은 11권이라, 첫 번째 책이 그룹을 두 번 맡아 보드에 6장
 *  등장합니다 - 대신 11권 전체가 파이널 레벨에 모두 등장합니다).
 * ------------------------------------------------------------
 */
